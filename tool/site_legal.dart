      <div class="footer-top">
        <a class="brand" href="./" aria-label="gramX home">
          <img class="on-dark" src="assets/brand/glyph-on-dark.png" alt="" width="24" height="26">
          <img class="on-light" src="assets/brand/glyph-on-light.png" alt="" width="24" height="26">
          <span>gramX</span>
        </a>
        <nav class="footer-links" aria-label="Footer">
          <a href="./#install">Download</a>
