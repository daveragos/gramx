// Writes the website's privacy policy and terms (docs/privacy.html and
// docs/terms.html) from lib/core/l10n/legal_text.dart, so the site and the
// app always say the same thing. Run it after changing either document:
//
//   dart run tool/site_legal.dart
import 'dart:io';

import 'package:gramx/core/l10n/legal_text.dart';

/// Where the site is published. Keep in step with docs/index.html.
const _siteUrl = 'https://daveragos.github.io/gramx/';

void main() {
  _write('privacy', LegalTexts.privacy);
  _write('terms', LegalTexts.terms);
}

void _write(String slug, LegalDocument doc) {
  final file = File('docs/$slug.html');
  file.writeAsStringSync(_page(slug, doc));
  stdout.writeln('Wrote ${file.path}');
}

String _escape(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');

/// Escapes [text] and links the contact address.
String _paragraph(String text) {
  const email = LegalTexts.contactEmail;
  return _escape(text).replaceAll(email, '<a href="mailto:$email">$email</a>');
}

String _icon(String id) =>
    '<svg class="i" aria-hidden="true"><use href="assets/icons.svg#i-$id"/></svg>';

String _page(String slug, LegalDocument doc) {
  final body = StringBuffer();
  for (final section in doc.sections) {
    body.writeln('    <h2>${_escape(section.heading)}</h2>');
    for (final p in section.paragraphs) {
      body.writeln('    <p>${_paragraph(p)}</p>');
    }
  }

  return '''<!doctype html>
<!-- Generated by tool/site_legal.dart from lib/core/l10n/legal_text.dart. Do not edit. -->
<html lang="en">
<head>
  <meta charset="utf-8">
