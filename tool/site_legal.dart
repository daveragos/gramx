        <span>gramX</span>
      </a>
      <div class="nav-actions">
        <button class="icon-btn theme-toggle" type="button" data-theme-cycle aria-label="Change theme">
          <svg class="i t-light" aria-hidden="true"><use href="assets/icons.svg#i-sun"/></svg>
          <svg class="i t-dim" aria-hidden="true"><use href="assets/icons.svg#i-dim"/></svg>
