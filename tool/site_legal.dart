  <meta name="description" content="${_escape(doc.summary)}">
  <link rel="canonical" href="$_siteUrl$slug.html">
  <meta name="theme-color" content="#000000">
  <link rel="icon" type="image/png" sizes="32x32" href="assets/favicon-32.png">
  <link rel="apple-touch-icon" href="assets/apple-touch-icon.png">
  <link rel="preload" href="assets/fonts/inter-latin.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="styles.css">
  <script>
    (function () {
      var d = document.documentElement, t = null;
      try { t = localStorage.getItem('gramx-theme'); } catch (e) {}
      if (t !== 'light' && t !== 'dim' && t !== 'dark') {
        t = window.matchMedia && matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
      }
      d.setAttribute('data-theme', t);
    })();
  </script>
  <script src="site.js" defer></script>
</head>
<body>
  <a class="skip" href="#main">Skip to content</a>

  <header class="nav" data-nav>
    <div class="container nav-inner">
      <a class="brand" href="./" aria-label="gramX home">
        <img class="on-dark" src="assets/brand/glyph-on-dark.png" alt="" width="24" height="26">
